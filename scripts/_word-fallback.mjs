export function wordFallback(english, locale) {
  const map = WORD_MAP[locale]
  if (!map) return english
  // Preserve placeholders
  const parts = english.split(/(\{[^}]+\})/g)
  return parts.map((part) => {
    if (part.startsWith('{')) return part
    return part.replace(/[A-Za-z']+/g, (word) => {
      const lower = word.toLowerCase()
      for (const [en, tr] of Object.entries(map)) {
        if (en.toLowerCase() === lower) return tr || word
      }
      return word
    })
  }).join('').replace(/\s+/g, ' ').trim()
}
