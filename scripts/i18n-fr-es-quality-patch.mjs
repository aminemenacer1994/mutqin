function setAt(obj, keyPath, value) {
  const parts = keyPath.split('.')
  let cursor = obj
  for (let i = 0; i < parts.length - 1; i += 1) {
    const part = parts[i]
    if (!cursor[part] || typeof cursor[part] !== 'object' || Array.isArray(cursor[part])) cursor[part] = {}
    cursor = cursor[part]
  }
  cursor[parts[parts.length - 1]] = value
}

function flatten(obj, prefix = '') {
  const out = {}
  for (const [k, v] of Object.entries(obj)) {
    const next = prefix ? `${prefix}.${k}` : k
    if (v && typeof v === 'object' && !Array.isArray(v)) Object.assign(out, flatten(v, next))
    else out[next] = v
  }
  return out
}

/** Copy English leaves that exist in en.json but are still missing from the locale tree. */
export function deepMergeMissing(target, source) {
  for (const [key, value] of Object.entries(source)) {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      if (!target[key] || typeof target[key] !== 'object' || Array.isArray(target[key])) target[key] = {}
      deepMergeMissing(target[key], value)
    } else if (target[key] === undefined) {
      target[key] = value
    }
  }
  return target
}

function applyPatch(tree, patch) {
  for (const [key, value] of Object.entries(patch)) {
    setAt(tree, key, value)
  }
}

function writeLocale(locale, patch) {
  const file = path.join(LOCALES_DIR, `${locale}.json`)
  const tree = JSON.parse(fs.readFileSync(file, 'utf8'))
  const en = JSON.parse(fs.readFileSync(path.join(LOCALES_DIR, 'en.json'), 'utf8'))
  applyPatch(tree, patch)
  deepMergeMissing(tree, en)
  fs.writeFileSync(file, `${JSON.stringify(tree, null, 2)}\n`)
  return flatten(tree)
}

function isMain() {
  const invoked = process.argv[1] ? path.resolve(process.argv[1]) : ''
  return invoked === fileURLToPath(import.meta.url)
}

if (isMain()) {
  const neededPath = path.join(ROOT, 'scripts/.i18n-fr-es-needed.json')
  const neededKeys = Object.keys(JSON.parse(fs.readFileSync(neededPath, 'utf8')))
  const missingFr = neededKeys.filter((k) => !(k in FR))
  const missingEs = neededKeys.filter((k) => !(k in ES))
  const extraFr = Object.keys(FR).filter((k) => !neededKeys.includes(k))
  const extraEs = Object.keys(ES).filter((k) => !neededKeys.includes(k))
  if (missingFr.length || missingEs.length || extraFr.length || extraEs.length) {
    console.error(`Map FR: ${Object.keys(FR).length} (missing ${missingFr.length}, extra ${extraFr.length})`)
    console.error(`Map ES: ${Object.keys(ES).length} (missing ${missingEs.length}, extra ${extraEs.length})`)
    if (missingFr.length) console.error('Missing FR:', missingFr.join(', '))
    if (missingEs.length) console.error('Missing ES:', missingEs.join(', '))
    process.exit(1)
  }

  const frFlat = writeLocale('fr', FR)
  const esFlat = writeLocale('es', ES)
  const absentFr = neededKeys.filter((k) => frFlat[k] === undefined)
  const absentEs = neededKeys.filter((k) => esFlat[k] === undefined)
  const appliedFr = neededKeys.filter((k) => frFlat[k] === FR[k]).length
  const appliedEs = neededKeys.filter((k) => esFlat[k] === ES[k]).length

  console.log(`FR keys written: ${Object.keys(FR).length}`)
  console.log(`ES keys written: ${Object.keys(ES).length}`)
  console.log(`Needed keys present in fr.json: ${neededKeys.length - absentFr.length}/${neededKeys.length}`)
  console.log(`Needed keys present in es.json: ${neededKeys.length - absentEs.length}/${neededKeys.length}`)
  console.log(`Applied FR values match map: ${appliedFr}/${neededKeys.length}`)
  console.log(`Applied ES values match map: ${appliedEs}/${neededKeys.length}`)
}
