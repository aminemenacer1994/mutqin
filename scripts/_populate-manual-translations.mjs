function translateText(english, locale) {
  if (QURAN_REMINDERS[locale]?.[english]) return QURAN_REMINDERS[locale][english]
  if (EXACT[locale]?.[english]) return EXACT[locale][english]

  let out = english
  for (const [re, repl] of GLOSSARY[locale] || []) {
    out = out.replace(re, repl)
  }
  return out
}

function loadSeedPatches(pending) {
  const syncSrc = fs.readFileSync(FULL_SYNC_PATH, 'utf8')
  const bulkSrc = fs.readFileSync(BULK_PATH, 'utf8')
  const memorisation = extractConst('MEMORISATION_PATCH', syncSrc)
  const coverage = extractConst('COVERAGE_PATCH', syncSrc)
  const bulk = extractConst('TRANSLATIONS', bulkSrc)
  /** @type {Record<string, Record<string, string>>} */
  const seeds = { ar: {}, es: {}, id: {}, tr: {} }

  for (const locale of LOCALES) {
    for (const patch of [memorisation[locale], coverage[locale]]) {
      if (!patch) continue
      for (const [key, value] of Object.entries(patch)) {
        if (pending[locale]?.[key]) seeds[locale][key] = value
      }
    }
    for (const [key, entry] of Object.entries(bulk)) {
      if (!pending[locale]?.[key]) continue
      if (entry[locale]) seeds[locale][key] = entry[locale]
      else if (locale === 'ar' && entry.ar) seeds[locale][key] = entry.ar
    }
  }

  const frFlat = flatten(JSON.parse(fs.readFileSync(path.join(LOCALES_DIR, 'fr.json'), 'utf8')))
  const enFlat = flatten(JSON.parse(fs.readFileSync(path.join(LOCALES_DIR, 'en.json'), 'utf8')))
  for (const [key, english] of Object.entries(pending.es || {})) {
    if (seeds.es[key]) continue
    if (frFlat[key] && frFlat[key] !== enFlat[key] && frFlat[key] !== english) {
      seeds.es[key] = translateText(frFlat[key], 'es')
    }
  }

  return seeds
}

function main() {
  const pending = JSON.parse(fs.readFileSync(PENDING_PATH, 'utf8'))
  const seeds = loadSeedPatches(pending)
  /** @type {Record<string, Record<string, string>>} */
  const manual = { ar: {}, es: {}, id: {}, tr: {} }

  for (const locale of LOCALES) {
    for (const [key, english] of Object.entries(pending[locale] || {})) {
      manual[locale][key] = seeds[locale][key] || translateText(english, locale)
    }
    console.log(`${locale}: ${Object.keys(manual[locale]).length} keys (${Object.keys(seeds[locale]).length} seeded)`)
  }

  fs.writeFileSync(OUT_PATH, `${JSON.stringify(manual, null, 2)}\n`)
  console.log(`Wrote ${OUT_PATH}`)
}

