import fs from 'node:fs'
import path from 'node:path'

const EXT_PATH = path.resolve('scripts/.i18n-exact-extended.json')
if (fs.existsSync(EXT_PATH)) {
  const ext = JSON.parse(fs.readFileSync(EXT_PATH, 'utf8'))
  for (const locale of ['ar', 'es', 'id', 'tr']) {
    const filtered = {}
    for (const [en, tr] of Object.entries(ext[locale] || {})) {
      if (locale === 'ar' && /[A-Za-z]{4,}/.test(tr) && !/\b(Mutqin|Tajweed|Enter|Ctrl|Alhamdulillah|Safari|iPhone|iPad|Beta|Settings|muraja|hifz|talqin|Masha|insha)\b/.test(tr)) {
        continue
      }
      filtered[en] = tr
    }
    EXACT[locale] = { ...EXACT[locale], ...filtered }
  }
}

