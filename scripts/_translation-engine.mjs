// Re-import full glossary from populate script at runtime
const POPULATE = fs.readFileSync(path.resolve('scripts/_populate-manual-translations.mjs'), 'utf8')
const GLOSSARY = Function(`return ${POPULATE.match(/const GLOSSARY = (\{[\s\S]*?\n\})\n\n\/\*\* Qur'anic/)[1]}`)()

export function translateText(english, locale) {
  if (QURAN_REMINDERS[locale]?.[english]) return QURAN_REMINDERS[locale][english]
  if (EXACT[locale]?.[english]) return EXACT[locale][english]

  /** @type {string[]} */
  const tokens = []
  const masked = english.replace(/\{[^}]+\}/g, (match) => {
    tokens.push(match)
    return `__PH${tokens.length - 1}__`
  })

  const rules = GLOSSARY[locale] || []
  for (const [re, repl] of rules) {
    const match = masked.match(re)
    if (match && match[0] === masked) return unmaskPlaceholders(masked.replace(re, repl), tokens)
  }
  let out = masked
  for (const [re, repl] of rules) out = out.replace(re, repl)
  return unmaskPlaceholders(out, tokens)
}

function unmaskPlaceholders(text, tokens) {
  let out = text
  tokens.forEach((token, index) => {
    out = out.replace(new RegExp(`__PH${index}__`, 'g'), token)
  })
  return out
}
