    <h1>A calmer, more structured way to memorise the Qur’an.</h1>
    <p>Mutqin is a Quran memorization app for Hifz. Listen, repeat, recite and review each ayah on a clear path. AI Recite can follow along when you practise from memory.</p>
    <h2>A clear path for every ayah</h2>
    <p>Set a short range, practise, recite, then return to what still needs care.</p>
    <h2>What supports your Hifz</h2>
    <p>Guided memorisation, listen and repeat, spaced review, AI Recite, Mushaf layout, and reading aids.</p>
    <h2>Questions about memorising with Mutqin</h2>
    <p>Mutqin is a Qur’an memorisation companion. It helps you listen, recite, review and return, and supports practice between lessons. It does not replace a teacher.</p>
