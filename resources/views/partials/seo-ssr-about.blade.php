    <section>
        <h2>Why we built Mutqin</h2>
        <p>
            Hifz asks for showing up again and again. Mutqin is a gentle workspace to pick up where you left off,
            revise what matters, and keep moving at your own pace.
        </p>
    </section>

    <section>
        <h2>How you might use it</h2>
        <ol>
            <li>Choose a short passage that feels doable today.</li>
            <li>Practise with memorisation techniques such as focus, blur, or chaining.</li>
            <li>Recite from memory when you feel ready.</li>
            <li>Listen back and notice what still needs care.</li>
            <li>Come back later. Your saved session will be waiting.</li>
        </ol>
    </section>

    <section>
        <h2>What you will find inside</h2>
        <ul>
            <li>Focus and blur to work one ayah at a time.</li>
            <li>Linking and chaining to connect ayahs during Quran memorisation.</li>
            <li>Saved sessions and progress tracking.</li>
            <li>Optional recitation feedback when you want a second listen.</li>
        </ul>
    </section>

    <section>
        <h2>With your teacher</h2>
        <p>
            Nothing replaces a qualified teacher for tajweed and correction.
            Mutqin is for the quiet days in between, when you are practising on your own.
        </p>
