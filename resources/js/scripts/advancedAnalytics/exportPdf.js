import { Chart, registerables } from 'chart.js'
import { jsPDF } from 'jspdf'
import { formatShortDate, todayIso } from './dateRange'
import { formatDuration } from './buildReportView'

Chart.register(...registerables)

const PAGE = {
  width: 210,
  height: 297,
  margin: 16,
}

const COLORS = {
  ink: [28, 25, 23],
  muted: [107, 99, 90],
  accent: [63, 111, 109],
  line: [210, 200, 185],
  soft: [247, 243, 236],
}

function contentWidth() {
  return PAGE.width - PAGE.margin * 2
}

function ensureSpace(doc, cursor, needed = 24) {
  if (cursor.y + needed <= PAGE.height - PAGE.margin - 12) return cursor
  doc.addPage()
  return { ...cursor, y: PAGE.margin, page: cursor.page + 1 }
}

function drawFooter(doc, page, total) {
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  doc.setTextColor(...COLORS.muted)
  doc.text('Generated by Mutqin — mutqin.ai', PAGE.margin, PAGE.height - 10)
  doc.text(`${page} / ${total}`, PAGE.width - PAGE.margin, PAGE.height - 10, { align: 'right' })
}

function sectionTitle(doc, cursor, title) {
  cursor = ensureSpace(doc, cursor, 18)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(13)
  doc.setTextColor(...COLORS.ink)
  doc.text(title, PAGE.margin, cursor.y)
  cursor.y += 4
  doc.setDrawColor(...COLORS.accent)
  doc.setLineWidth(0.4)
  doc.line(PAGE.margin, cursor.y, PAGE.margin + 28, cursor.y)
  cursor.y += 8
  return cursor
}

function bodyText(doc, cursor, text, { size = 10, color = COLORS.ink, gap = 5 } = {}) {
  const lines = doc.splitTextToSize(String(text || ''), contentWidth())
  cursor = ensureSpace(doc, cursor, lines.length * (size * 0.45) + gap)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(size)
  doc.setTextColor(...color)
  doc.text(lines, PAGE.margin, cursor.y)
  cursor.y += lines.length * (size * 0.45) + gap
  return cursor
}

function renderArabicLabel(text, { width = 220, height = 28, fontSize = 16 } = {}) {
  const value = String(text || '').trim()
  if (!value || typeof document === 'undefined') return null
  const canvas = document.createElement('canvas')
  const scale = 2
  canvas.width = width * scale
  canvas.height = height * scale
  const ctx = canvas.getContext('2d')
  if (!ctx) return null
  ctx.scale(scale, scale)
  ctx.clearRect(0, 0, width, height)
  ctx.fillStyle = '#1c1917'
  ctx.font = `${fontSize}px "Noto Naskh Arabic", "Amiri", "Scheherazade New", "Arial", sans-serif`
  ctx.textAlign = 'right'
  ctx.textBaseline = 'middle'
  ctx.direction = 'rtl'
  ctx.fillText(value, width - 4, height / 2)
  return canvas.toDataURL('image/png')
}

async function chartToImage(config, { width = 720, height = 280 } = {}) {
  if (typeof document === 'undefined' || !config?.data) return null
  const canvas = document.createElement('canvas')
  canvas.width = width
  canvas.height = height
  canvas.style.width = `${width}px`
  canvas.style.height = `${height}px`
  const chart = new Chart(canvas.getContext('2d'), {
    type: config.type || 'line',
    data: config.data,
    options: {
      ...(config.options || {}),
      responsive: false,
      animation: false,
      devicePixelRatio: 2,
    },
  })
  await new Promise((resolve) => requestAnimationFrame(() => resolve()))
  const url = canvas.toDataURL('image/png')
  chart.destroy()
  return url
}

function kpiGrid(doc, cursor, cards) {
  const cols = 2
  const gap = 4
  const cardW = (contentWidth() - gap) / cols
  const cardH = 22
  cards.forEach((card, index) => {
    const col = index % cols
    if (col === 0) cursor = ensureSpace(doc, cursor, cardH + 4)
    const x = PAGE.margin + col * (cardW + gap)
    const y = cursor.y
    doc.setFillColor(...COLORS.soft)
    doc.roundedRect(x, y, cardW, cardH, 2, 2, 'F')
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8)
    doc.setTextColor(...COLORS.muted)
    doc.text(String(card.title || ''), x + 3, y + 6)
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(12)
    doc.setTextColor(...COLORS.ink)
    doc.text(String(card.value || '—'), x + 3, y + 13)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(7)
    doc.setTextColor(...COLORS.muted)
    const hint = doc.splitTextToSize(String(card.description || ''), cardW - 6)
    doc.text(hint.slice(0, 1), x + 3, y + 18)
    if (col === cols - 1 || index === cards.length - 1) {
      cursor.y += cardH + gap
    }
  })
  cursor.y += 2
  return cursor
}

function drawChartImage(doc, cursor, image, { height = 58 } = {}) {
  if (!image) return cursor
  cursor = ensureSpace(doc, cursor, height + 4)
  doc.addImage(image, 'PNG', PAGE.margin, cursor.y, contentWidth(), height)
  cursor.y += height + 8
  return cursor
}

function surahTable(doc, cursor, rows, t) {
  if (!rows.length) return cursor
  cursor = sectionTitle(doc, cursor, t('dashboard.advanced_analytics.pdf_surah_progress'))
  rows.slice(0, 12).forEach((row) => {
    cursor = ensureSpace(doc, cursor, 16)
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(10)
    doc.setTextColor(...COLORS.ink)
    doc.text(String(row.surah_name || `Surah ${row.surah_number}`), PAGE.margin, cursor.y)
    if (row.surah_name_ar) {
      const arabic = renderArabicLabel(row.surah_name_ar, { width: 160, height: 18, fontSize: 12 })
      if (arabic) {
        doc.addImage(arabic, 'PNG', PAGE.width - PAGE.margin - 40, cursor.y - 5, 40, 8)
      }
    }
    cursor.y += 5
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8)
    doc.setTextColor(...COLORS.muted)
    doc.text(
      t('dashboard.advanced_analytics.surah_meta', {
        practised: row.ayahs_practised || 0,
        memorised: row.ayahs_memorised || 0,
        revised: row.revision_coverage || 0,
        last: row.last_label || '—',
      }),
      PAGE.margin,
      cursor.y,
    )
    cursor.y += 4
    const barW = contentWidth()
    doc.setFillColor(...COLORS.line)
    doc.roundedRect(PAGE.margin, cursor.y, barW, 2.2, 1, 1, 'F')
    doc.setFillColor(...COLORS.accent)
    doc.roundedRect(
      PAGE.margin,
      cursor.y,
      barW * (Math.max(0, Math.min(100, Number(row.memorised_percent || 0))) / 100),
      2.2,
      1,
      1,
      'F',
    )
    cursor.y += 8
  })
  return cursor
}

function attentionTable(doc, cursor, rows, t) {
  if (!rows.length) return cursor
  cursor = sectionTitle(doc, cursor, t('dashboard.advanced_analytics.pdf_attention'))
  rows.slice(0, 10).forEach((row) => {
    cursor = ensureSpace(doc, cursor, 12)
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(10)
    doc.setTextColor(...COLORS.ink)
    doc.text(row.label, PAGE.margin, cursor.y)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(9)
    doc.setTextColor(...COLORS.muted)
    doc.text(row.accuracy_label, PAGE.width - PAGE.margin, cursor.y, { align: 'right' })
    cursor.y += 4
    const detail = [row.attempts_label, row.classifications_label, row.last_label].filter(Boolean).join(' · ')
    if (detail) {
      doc.setFontSize(8)
      doc.text(doc.splitTextToSize(detail, contentWidth()), PAGE.margin, cursor.y)
      cursor.y += 6
    } else {
      cursor.y += 4
    }
  })
  return cursor
}

/**
 * Generate and download Mutqin_Analytics_YYYY-MM-DD.pdf from the shared report view.
 */
export async function exportAdvancedAnalyticsPdf(view, t) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'portrait' })
  let cursor = { y: PAGE.margin, page: 1 }
  const generatedOn = formatShortDate(todayIso())
  const fileDate = todayIso()

  // Page 1 — Overview
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(18)
  doc.setTextColor(...COLORS.accent)
  doc.text('Mutqin', PAGE.margin, cursor.y)
  cursor.y += 8
  doc.setFontSize(16)
  doc.setTextColor(...COLORS.ink)
  doc.text(t('dashboard.advanced_analytics.pdf_title'), PAGE.margin, cursor.y)
  cursor.y += 7
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  doc.setTextColor(...COLORS.muted)
  if (view.userName) {
    doc.text(view.userName, PAGE.margin, cursor.y)
    cursor.y += 5
  }
  doc.text(t('dashboard.advanced_analytics.pdf_period', { period: view.periodLabel || '—' }), PAGE.margin, cursor.y)
  cursor.y += 5
  doc.text(t('dashboard.advanced_analytics.pdf_generated', { date: generatedOn }), PAGE.margin, cursor.y)
  cursor.y += 10

  cursor = sectionTitle(doc, cursor, t('dashboard.advanced_analytics.pdf_overview'))
  cursor = kpiGrid(doc, cursor, view.cards || [])

  if (view.practiceChart) {
    cursor = sectionTitle(doc, cursor, t('dashboard.advanced_analytics.chart_practice_title'))
    const image = await chartToImage({ type: 'line', ...view.practiceChart }, { width: 860, height: 300 })
    cursor = drawChartImage(doc, cursor, image, { height: 62 })
  }

  // Page 2 — Learning progress
  if ((view.sessionMixChart || view.surahProgress?.length || view.hasPractice)) {
    doc.addPage()
    cursor = { y: PAGE.margin, page: cursor.page + 1 }
    cursor = sectionTitle(doc, cursor, t('dashboard.advanced_analytics.pdf_progress'))
    if (view.sessionMixChart) {
      cursor = bodyText(doc, cursor, t('dashboard.advanced_analytics.chart_mix_title'), { size: 11, gap: 4 })
      const mixImage = await chartToImage({ type: 'bar', ...view.sessionMixChart }, { width: 860, height: 280 })
      cursor = drawChartImage(doc, cursor, mixImage, { height: 58 })
    }
    if (view.overview) {
      cursor = bodyText(
        doc,
        cursor,
        t('dashboard.advanced_analytics.pdf_consistency_summary', {
          days: view.overview.practice_days || 0,
          time: formatDuration(view.overview.practice_time_seconds, t),
          ayahs: view.overview.ayahs_practised || 0,
        }),
        { size: 10, color: COLORS.muted, gap: 8 },
      )
    }
    cursor = surahTable(doc, cursor, view.surahProgress || [], t)
  }

  // Page 3 — AI analysis
  if (view.hasAi || view.attention?.length) {
    doc.addPage()
    cursor = { y: PAGE.margin, page: cursor.page + 1 }
    cursor = sectionTitle(doc, cursor, t('dashboard.advanced_analytics.pdf_ai'))
    if (view.aiChart) {
      cursor = bodyText(doc, cursor, t('dashboard.advanced_analytics.chart_ai_title'), { size: 11, gap: 4 })
      const aiImage = await chartToImage({ type: 'line', ...view.aiChart }, { width: 860, height: 260 })
      cursor = drawChartImage(doc, cursor, aiImage, { height: 54 })
    }
    if (view.breakdownChart) {
      cursor = bodyText(doc, cursor, t('dashboard.advanced_analytics.chart_breakdown_title'), { size: 11, gap: 4 })
      const donut = await chartToImage({ type: 'doughnut', ...view.breakdownChart }, { width: 420, height: 280 })
      cursor = drawChartImage(doc, cursor, donut, { height: 55 })
    }
    cursor = attentionTable(doc, cursor, view.attention || [], t)
  }

  // Page 4 — Insights
  if (view.insights?.length) {
    doc.addPage()
    cursor = { y: PAGE.margin, page: cursor.page + 1 }
    cursor = sectionTitle(doc, cursor, t('dashboard.advanced_analytics.pdf_insights'))
    view.insights.forEach((insight) => {
      cursor = ensureSpace(doc, cursor, 14)
      doc.setFillColor(...COLORS.soft)
      doc.roundedRect(PAGE.margin, cursor.y - 4, contentWidth(), 12, 2, 2, 'F')
      doc.setFont('helvetica', 'normal')
      doc.setFontSize(10)
      doc.setTextColor(...COLORS.ink)
      const lines = doc.splitTextToSize(insight.text, contentWidth() - 8)
      doc.text(lines.slice(0, 2), PAGE.margin + 3, cursor.y + 2)
      cursor.y += Math.max(14, lines.slice(0, 2).length * 5 + 6)
    })
    cursor = bodyText(
      doc,
      cursor,
      t('dashboard.advanced_analytics.pdf_summary', { period: view.periodLabel || '—' }),
      { size: 10, color: COLORS.muted, gap: 6 },
    )
  }

  const total = doc.getNumberOfPages()
  for (let page = 1; page <= total; page += 1) {
    doc.setPage(page)
    drawFooter(doc, page, total)
  }

  doc.save(`Mutqin_Analytics_${fileDate}.pdf`)
}
