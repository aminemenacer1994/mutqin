const { chromium } = require('playwright')

async function main() {
  const browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await page.goto('http://localhost:8000/login', { waitUntil: 'domcontentloaded' })
  await page.locator('input[type=email]').fill('org.demo.halaqa.teacher@example.com')
  await page.locator('input[type=password]').fill('OrganisationDemo1!')
  await page.getByRole('button', { name: /login/i }).click()
  await page.waitForURL('**/teacher')
  await page.locator('.teacher-nav-shell--desktop').getByRole('button', { name: 'Tasks' }).click()
  await page.getByRole('button', { name: /add task/i }).click()

  const dialog = page.getByRole('dialog')
  await dialog.locator('select[id$="-student"]').selectOption({ index: 1 })
  await dialog.locator('select[id$="-surah"]').selectOption('2')
  await dialog.locator('input[id$="-from"]').fill('4')
  await dialog.locator('input[id$="-to"]').fill('2')
  if (await dialog.getByRole('button', { name: 'Send' }).isEnabled()) throw new Error('Invalid ayah range allowed')
  await dialog.locator('input[id$="-from"]').fill('1')
  await dialog.locator('input[id$="-reps"]').fill('2')
  await dialog.locator('textarea[id$="-feedback"]').fill('QA task to remove after verification')
  const createResponse = page.waitForResponse((response) => response.url().endsWith('/teacher/assignments') && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Send' }).click()
  const created = await (await createResponse).json()
  const id = created.assignment.id
  if (!id) throw new Error('Task creation did not return an id')

  await page.locator('.teacher-search--tasks input').fill('Al-Baqarah')
  const row = page.locator('.teacher-task-list li').filter({ hasText: 'Al-Baqarah 1–2' }).first()
  await row.waitFor()
  await row.getByRole('button', { name: /edit task/i }).click()
  if (!await dialog.locator('select[id$="-student"]').isDisabled()) throw new Error('Edit allowed changing student')
  await dialog.locator('input[id$="-to"]').fill('3')
  const updateResponse = page.waitForResponse((response) => response.url().endsWith(`/teacher/assignments/${id}`) && response.request().method() === 'PUT')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  const updated = await (await updateResponse).json()
  if (updated.assignment.ayah_end !== 3) throw new Error('Edited range did not persist')

  const updatedRow = page.locator('.teacher-task-list li').filter({ hasText: 'Al-Baqarah 1–3' }).first()
  await updatedRow.waitFor()
  await updatedRow.getByRole('button', { name: /remove task/i }).click()
  const removeDialog = page.getByRole('dialog')
  if (!await removeDialog.getByText(/Remove Al-Baqarah/).count()) throw new Error('Delete confirmation missing task context')
  const removeResponse = page.waitForResponse((response) => response.url().endsWith(`/teacher/assignments/${id}`) && response.request().method() === 'DELETE')
  await removeDialog.getByRole('button', { name: 'Remove task' }).click()
  const removed = await (await removeResponse).json()
  if (!removed.removed) throw new Error('Task removal did not succeed')
  await page.getByRole('status').filter({ hasText: 'Task removed.' }).waitFor()
  console.log(JSON.stringify({ created: id, updatedTo: updated.assignment.ayah_end, removed: removed.removed, invalidRangeBlocked: true }))
  await browser.close()
}

main().catch((error) => { console.error(error); process.exit(1) })
