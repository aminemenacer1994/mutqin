import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const plan = readFileSync(new URL('../../resources/js/components/teacher/profile/TeacherStudentProfilePlan.vue', import.meta.url), 'utf8')
const css = readFileSync(new URL('../../resources/js/views/TeacherDashboard.css', import.meta.url), 'utf8')
const template = plan.slice(plan.indexOf('<template>'), plan.indexOf('<script>'))
const composerStart = template.indexOf('ref="dialog"')
const composer = template.slice(composerStart, template.indexOf('TeacherRecitationPlaybackReview'))

assert.ok(composer.includes('teacher-plan-steps'), 'The composer shows the step list')
const details = composer.indexOf('plan_step_details')
const activities = composer.indexOf('plan_step_activities')
const review = composer.indexOf('plan_step_review')
assert.ok(details > 0 && activities > details && review > activities, 'Steps stay in details, activities, review order')
assert.match(composer, /v-show="step === 1"/, 'Plan details stay mounted between steps')
assert.match(composer, /v-show="step === 2"/, 'Activities stay mounted between steps')
assert.match(composer, /v-show="step === 3"/, 'Review stays mounted between steps')
assert.match(composer, /passageLabel\(item\)/, 'Each activity card shows its passage')
assert.match(composer, /activityLabel\(item\)/, 'Each activity card shows its type and memorisation stage')
assert.match(plan, /hifz_category: item\?\.hifz_category/, 'The shared activity label receives the memorisation category')
assert.match(composer, /scheduleLabel\(item\)/, 'Each activity card shows its schedule')
assert.match(composer, /itemStatusLabel\(item\)/, 'Each activity card shows its status')
assert.match(composer, /plan_add_activity/, 'Activities can be added')
assert.match(composer, /plan_edit_activity/, 'Activities can be edited')
assert.match(composer, /removeDraftItem/, 'Activities can be removed')
assert.match(composer, /plan_save_draft/, 'Save draft stays available')
assert.match(composer, /teacher-plan-dialog__activate/, 'Activate is a separate action')
assert.match(composer, /activationCopy/, 'The review step explains what activation does')
assert.match(plan, /plan_activate_explainer/, 'Activation explains student assignments')
assert.match(plan, /plan_save_explainer/, 'Saving an active plan explains that it does not create assignments')
assert.match(composer, /plan_suggestions/, 'Suggested revisions stay in the activity step')
assert.match(plan, /origin: 'suggested'/, 'Suggestions are not assigned until the teacher approves them')
assert.match(plan, /activate: willActivate/, 'A draft save does not activate the plan')
assert.match(plan, /setTeacherLearningPlanStatus\(planId, 'active'\)/, 'Activating an edited draft uses the existing status API')
assert.match(plan, /activityId\(left\) === activityId\(right\)/, 'Duplicate activities use the same learning type')
assert.match(plan, /repetition_target/, 'The activity target is saved with the plan')
assert.match(css, /\.teacher-plan-dialog \.modal-body \{[^}]*overflow-y: auto/, 'The plan modal body scrolls')
assert.match(css, /\.teacher-plan-dialog \.modal-footer \{[^}]*padding: 12px 16px calc\(14px \+ env\(safe-area-inset-bottom\)\)/, 'The plan footer keeps bottom padding')
assert.match(css, /\.teacher-dialog\.teacher-plan-dialog \.modal-footer \{[^}]*flex-direction: column/, 'Plan actions stack on a narrow screen')

console.log('teacher plan composer ok')
