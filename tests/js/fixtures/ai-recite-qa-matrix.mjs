function assertMatrixIntegrity() {
  if (aiReciteQaMatrix.length !== 100) {
    throw new Error(`AI Recite QA matrix must contain 100 scenarios, got ${aiReciteQaMatrix.length}`)
  }
  const ids = new Set(aiReciteQaMatrix.map((row) => row.id))
  if (ids.size !== 100) throw new Error('Duplicate AIR ids in QA matrix')
  for (let i = 1; i <= 100; i += 1) {
    const id = `AIR-${String(i).padStart(3, '0')}`
    if (!ids.has(id)) throw new Error(`Missing ${id} in QA matrix`)
  }
}
