export function qaScenarioById(id) {
  const row = aiReciteQaMatrix.find((item) => item.id === id)
  if (!row) throw new Error(`Unknown AI Recite QA scenario: ${id}`)
  return row
}

export function edgeScenarioForQa(row) {
  if (!row.edgeId) return null
  return edgeById[row.edgeId] || null
}

